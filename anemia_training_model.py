    hist_b = cv2.calcHist([ (nail[:, :, 0] * 255).astype(np.uint8) ], [0], None, [32], [0, 256]).flatten()

    hist = np.hstack((hist_r, hist_g, hist_b))
    hist = hist / (hist.sum() + 1e-6)

    features = np.hstack([ [mean_r, mean_g, mean_b, brightness, contrast], hist ])
    return features

