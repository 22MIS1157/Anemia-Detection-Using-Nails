def extract_nail_regions(image, bboxes=None):
    """
    Extract nail crops from a hand image.
    If bounding boxes are provided, use them directly; otherwise use Otsu thresholding.
    """
    if image is None:
        raise ValueError("Input image is None. Check if the image path is correct.")

    nails = []
    if bboxes:
        for box in bboxes:
            if len(box) != 4:
                continue  # skip invalid boxes
            x, y, w, h = box
            nail = image[y:y+h, x:x+w]
            nails.append(nail)
        return nails

    # Fallback: simple segmentation
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    _, thresh = cv2.threshold(gray, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)
    kernel = np.ones((5, 5), np.uint8)
    mask = cv2.morphologyEx(thresh, cv2.MORPH_OPEN, kernel, iterations=1)
    cnts, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    for cnt in cnts:
        x, y, w, h = cv2.boundingRect(cnt)
        if w * h > 1000:  # filter noise
            nails.append(image[y:y+h, x:x+w])
    return nails

