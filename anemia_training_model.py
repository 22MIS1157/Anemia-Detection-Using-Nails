class DualAttentionBlock(nn.Module):
    """Dual resolution windowed self-attention block"""
    def __init__(self, in_channels, num_heads=4, window_size=7):
        super().__init__()
        self.window_size = window_size
        self.num_heads = num_heads
        self.head_dim = in_channels // num_heads
        self.scale = (self.head_dim) ** -0.5
        self.qkv = nn.Linear(in_channels, in_channels * 3)
        self.proj = nn.Linear(in_channels, in_channels)
        self.norm = nn.LayerNorm(in_channels)

    def window_partition(self, x):
        B, C, H, W = x.shape
        x = x.view(B, C, H // self.window_size, self.window_size, W // self.window_size, self.window_size)
        x = x.permute(0, 2, 4, 1, 3, 5).contiguous()
        x = x.view(-1, self.window_size * self.window_size, C)
        return x

    def window_reverse(self, windows, H, W):
        B = int(windows.shape[0] / (H * W / self.window_size ** 2))
        x = windows.view(B, H // self.window_size, W // self.window_size, self.window_size, self.window_size, -1)
        x = x.permute(0, 3, 1, 4, 2, 5).contiguous()
        x = x.view(B, -1, H, W)
        return x

    def forward(self, x):
        B, C, H, W = x.shape
        x_window = self.window_partition(x)
        N = x_window.shape[0]
        qkv = self.qkv(x_window).reshape(N, -1, 3, self.num_heads, self.head_dim).permute(2, 0, 3, 1, 4)
        q, k, v = qkv[0], qkv[1], qkv[2]
        attn = (q @ k.transpose(-2, -1)) * self.scale
        attn = F.softmax(attn, dim=-1)
        x = (attn @ v).transpose(1, 2).reshape(N, -1, C)
        x = self.proj(x)
        x = self.window_reverse(x, H, W)
        x = x.permute(0, 2, 1, 3).reshape(B, C, H, W)
        x = self.norm(x.permute(0, 2, 3, 1)).permute(0, 3, 1, 2)
        return x

class NovelHybridCNNTransformer(nn.Module):
    def __init__(self, num_classes=2, in_channels=3, feature_channels=256, window_size=7):
        super().__init__()
        # CNN backbone (simplified, can be replaced with ResNet/EfficientNet)
        self.backbone = nn.Sequential(
            nn.Conv2d(in_channels, 64, kernel_size=7, stride=2, padding=3),
            nn.BatchNorm2d(64),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(kernel_size=3, stride=2, padding=1),
            nn.Conv2d(64, 128, kernel_size=3, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(kernel_size=3, stride=2, padding=1),
            nn.Conv2d(128, feature_channels, kernel_size=3, padding=1),
            nn.BatchNorm2d(feature_channels),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(kernel_size=3, stride=2, padding=1)
        )
        # Dual resolution self-attention
        self.dual_attention = DualAttentionBlock(feature_channels, window_size=window_size)
        # Class evidence map generator (convolutional classifier)
        self.evidence_map = nn.Sequential(
            nn.Conv2d(feature_channels, num_classes, kernel_size=1),
            nn.Upsample(scale_factor=8, mode='bilinear', align_corners=False)
        )
        # Global average pooling for final prediction
        self.avgpool = nn.AdaptiveAvgPool2d((1, 1))
        # Loss sparsity hyperparameter
        self.sparsity_lambda = 0.01

    def forward(self, x):
        # Feature extraction
        features = self.backbone(x)
        # Dual resolution self-attention
        features = self.dual_attention(features)
        # Class evidence maps
        evidence = self.evidence_map(features)
        # Final prediction
        pred = self.avgpool(evidence)
        pred = pred.view(pred.size(0), -1)
        # Return prediction and evidence maps
        return pred, evidence

    def get_loss(self, pred, evidence, target):
        ce_loss = F.cross_entropy(pred, target)
        sparsity_loss = self.sparsity_lambda * torch.mean(torch.abs(evidence))
        return ce_loss + sparsity_loss

