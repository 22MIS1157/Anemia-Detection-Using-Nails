    def __init__(self):
        super(QuantumPyramidAttentionNet, self).__init__()
        self.conv1 = nn.Conv2d(3, 32, 3, padding=1)
        self.conv2 = nn.Conv2d(32, 64, 3, padding=1)
        self.pool = nn.MaxPool2d(2, 2)
        self.dropout = nn.Dropout(0.3)
        self.q_attention = QuantumAttentionLayer()
        self.fc1 = nn.Linear(64 * 8 * 8 + 4, 128)
        self.fc2 = nn.Linear(128, 2)  # Binary classification: anemic vs healthy

