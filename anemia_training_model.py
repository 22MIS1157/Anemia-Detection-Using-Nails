# ✅ STEP 3: Define Quantum Circuit for Attention (QNode)
dev = qml.device("default.qubit", wires=4)

@qml.qnode(dev, interface="torch")
def quantum_attention(inputs):
    for i in range(4):
        qml.RY(inputs[i], wires=i)
    for i in range(3):
        qml.CNOT(wires=[i, i + 1])
    return [qml.expval(qml.PauliZ(i)) for i in range(4)]

# ✅ STEP 4: Define the Quantum Layer
class QuantumAttentionLayer(nn.Module):
    def __init__(self):
        super(QuantumAttentionLayer, self).__init__()
        self.q_params = nn.Parameter(torch.rand(4))

    def forward(self, x):
        batch_size = x.shape[0]
        q_out = []
        for i in range(batch_size):
            q_input = self.q_params
            q_result = quantum_attention(q_input)
            q_out.append(q_result)
        return torch.tensor(q_out, dtype=torch.float32)

# ✅ STEP 5: Define the Hybrid CNN + Pyramid + Quantum Attention Model
