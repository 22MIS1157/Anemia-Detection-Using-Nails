class AnemiaClassifier:
    def __init__(self, model_path):
        self.model = ConvPyramidTransformerCBAM()
        self.model.load_state_dict(torch.load(model_path, map_location=DEVICE))
        self.model.eval()
        self.model.to(DEVICE)
        self.detector = NailDetector()
        self.classes = ['Healthy', 'Anemic']

    def classify_single_nail(self, nail_image):
        """Classify a single nail image"""
        # Enhance the nail image
        enhanced_nail = self.detector.enhance_nail_image(nail_image)

        # Convert to PIL and apply transforms
        pil_image = Image.fromarray(enhanced_nail)
        tensor_image = self.detector.transform(pil_image).unsqueeze(0).to(DEVICE)

        with torch.no_grad():
            outputs = self.model(tensor_image)
            probabilities = F.softmax(outputs, dim=1)
            predicted_class = torch.argmax(probabilities, dim=1).item()
            confidence = probabilities[0][predicted_class].item()

        return {
            'class': self.classes[predicted_class],
            'confidence': confidence,
            'probabilities': probabilities[0].cpu().numpy()
        }

    def classify_patient_hand(self, hand_image_path):
        """Classify patient anemia status from hand image"""
        # Detect nails
        nail_regions = self.detector.detect_fingernails(hand_image_path)

        if len(nail_regions) == 0:
            return {
                'status': 'Error',
                'message': 'No nails detected in the image',
                'nail_results': []
            }

        # Classify each nail
        nail_results = []
        anemic_votes = 0
        total_confidence = 0

        for i, nail_region in enumerate(nail_regions):
            result = self.classify_single_nail(nail_region['image'])
            nail_results.append({
                'nail_id': i + 1,
                'bbox': nail_region['bbox'],
                'classification': result['class'],
                'confidence': result['confidence'],
                'probabilities': result['probabilities']
            })

            if result['class'] == 'Anemic':
                anemic_votes += 1

            total_confidence += result['confidence']

        # Make final decision based on majority voting with confidence weighting
        avg_confidence = total_confidence / len(nail_results)
        anemic_ratio = anemic_votes / len(nail_results)

        # Decision logic: If more than 50% nails are anemic, classify as anemic
        final_status = 'Anemic' if anemic_ratio > 0.5 else 'Healthy'

        return {
            'status': final_status,
            'confidence': avg_confidence,
            'anemic_ratio': anemic_ratio,
            'nails_detected': len(nail_regions),
            'anemic_nails': anemic_votes,
            'nail_results': nail_results
        }

