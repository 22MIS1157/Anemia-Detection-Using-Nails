    mean_b = np.mean(nail[:,:,0])
    # Compute brightness (mean of gray)
    gray = rgb2gray(nail)
    brightness = np.mean(gray)
    # Compute simple contrast texture via gray-level co-occurrence matrix (GLCM)
    # (Requires integer image for greycomatrix, so scale 0-255)
