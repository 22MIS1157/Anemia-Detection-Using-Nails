# --- NAIL DETECTION AND SEGMENTATION CLASS ---
class NailDetector:
    def __init__(self):
        self.transform = transforms.Compose([
            transforms.Resize((IMAGE_SIZE, IMAGE_SIZE)),
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
        ])

    def detect_hand_region(self, image):
        """Detect hand region using skin color segmentation"""
        img_rgb = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        # Convert to HSV for better skin detection
        hsv = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2HSV)

        # Define skin color range in HSV
        lower_skin = np.array([0, 20, 70])
        upper_skin = np.array([20, 255, 255])

        mask = cv2.inRange(hsv, lower_skin, upper_skin)

        # Clean up the mask
        kernel = np.ones((3,3), np.uint8)
        mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, kernel)
        mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, kernel)

        return mask

    def detect_fingernails(self, image):
        """Detect individual fingernails from hand image"""
        if isinstance(image, str):
            image = cv2.imread(image)

        original_image = image.copy()
        height, width = image.shape[:2]

        # Convert to grayscale
        gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

        # Detect hand region
        hand_mask = self.detect_hand_region(image)

        # Apply Gaussian blur
        blurred = cv2.GaussianBlur(gray, (5, 5), 0)

        # Threshold to find nail regions (nails are typically lighter)
        _, thresh = cv2.threshold(blurred, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)

        # Combine with hand mask
        thresh = cv2.bitwise_and(thresh, hand_mask)

        # Find contours
        contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        # Filter contours based on area and aspect ratio
        nail_regions = []
        min_area = (width * height) * 0.001  # Minimum 0.1% of image
        max_area = (width * height) * 0.05   # Maximum 5% of image

        for contour in contours:
            area = cv2.contourArea(contour)
            if min_area < area < max_area:
                # Get bounding rectangle
                x, y, w, h = cv2.boundingRect(contour)
                aspect_ratio = w / h

                # Nails typically have aspect ratio between 0.6 and 1.8
                if 0.6 <= aspect_ratio <= 1.8:
                    # Add some padding
                    padding = 10
                    x = max(0, x - padding)
                    y = max(0, y - padding)
                    w = min(width - x, w + 2 * padding)
                    h = min(height - y, h + 2 * padding)

                    nail_region = original_image[y:y+h, x:x+w]
                    if nail_region.size > 0:
                        nail_regions.append({
                            'image': nail_region,
                            'bbox': (x, y, w, h),
                            'area': area
                        })

        # Sort by y-coordinate (top to bottom) then x-coordinate (left to right)
        nail_regions.sort(key=lambda x: (x['bbox'][1], x['bbox'][0]))

        return nail_regions

    def enhance_nail_image(self, nail_image):
        """Enhance nail image for better classification"""
        # Convert to RGB
        if len(nail_image.shape) == 3 and nail_image.shape[2] == 3:
            nail_rgb = cv2.cvtColor(nail_image, cv2.COLOR_BGR2RGB)
        else:
            nail_rgb = nail_image

        # Apply CLAHE (Contrast Limited Adaptive Histogram Equalization)
        lab = cv2.cvtColor(nail_rgb, cv2.COLOR_RGB2LAB)
        l, a, b = cv2.split(lab)
        clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8,8))
        l = clahe.apply(l)
        enhanced = cv2.merge([l, a, b])
        enhanced = cv2.cvtColor(enhanced, cv2.COLOR_LAB2RGB)

        return enhanced

